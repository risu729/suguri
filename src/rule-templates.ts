function template(
  id: string,
  name: string,
  description: string,
  requiresChannel: boolean,
  values: Partial<RuleTemplate["rule"]>,
): RuleTemplate {
  return {
    id,
    name,
    description,
    requiresChannel,
    rule: {
      name,
      priority: 100,
      enabled: true,
      action: "categorize",
      titleIncludes: [],
      titleExcludes: [],
      descriptionIncludes: [],
      minDurationSeconds: null,
      maxDurationSeconds: null,
      kind: "any",
      ...values,
    },
  };
}

